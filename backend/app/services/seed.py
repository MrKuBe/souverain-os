logger = logging.getLogger(__name__)
settings = get_settings()

DEMO_AUDIT_NAME = "GHT Grand Lac — Démonstration publique (fictif)"
DEMO_ESTABLISHMENTS = [
    "CHU Support",
    "CH Jean-Moulin",
    "CH Sainte-Marie",
    "GHT Grand Lac",
]


def seed_database() -> None:
    with Session(engine) as session:
        admin = _ensure_initial_admin(session)
        if settings.seed_demo_data:
            _ensure_demo_audit(session, admin)


def _ensure_initial_admin(session: Session) -> User:
    existing = find_user_by_username(session, settings.admin_username)
    if existing is not None:
        logger.info("Compte administrateur initial déjà présent : aucun écrasement.")
        return existing
    if settings.uses_placeholder_admin_password:
        logger.warning(
            "ADMIN_PASSWORD utilise la valeur d'exemple : à remplacer avant tout usage réel."
        )
    admin = User(
        username=settings.admin_username,
        email=settings.admin_email,
        full_name=settings.admin_full_name,
        hashed_password=hash_password(settings.admin_password),
        role="admin_ght",
        auth_source="local",
        is_active=True,
    )
    session.add(admin)
    session.commit()
    session.refresh(admin)
    logger.info("Compte administrateur initial créé : %s", admin.username)
    return admin


def _ensure_demo_audit(session: Session, admin: User) -> None:
    existing = session.exec(select(Audit).where(Audit.is_demo.is_(True))).first()
    if existing is not None:
        logger.info("Jeu de démonstration déjà présent : seed ignoré.")
        return

    audit = Audit(
        name=DEMO_AUDIT_NAME,
        description=(
            "Jeu de démonstration fictif, public et strictement en lecture seule. "
            "Aucune donnée réelle de patient ou d'établissement."
        ),
        ght_name="GHT Grand Lac (fictif)",
        establishments=DEMO_ESTABLISHMENTS,
        is_demo=True,
        created_by_id=admin.id,
    )
    session.add(audit)
    session.flush()

    for payload in _demo_bricks():
        session.add(ApplicationBrick(audit_id=audit.id, **payload))
    session.commit()
    logger.info("Jeu de démonstration chargé : %s briques.", len(_demo_bricks()))


